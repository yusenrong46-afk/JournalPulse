"""Fill upgrade/RESUME_BULLETS.md's bullets from generated evidence, or check that they match.

    uv run python scripts/resume_numbers.py --write     # after make eval / onboard / drill
    uv run python scripts/resume_numbers.py --check     # make check-l5-docs

Every number in the bullets comes from a file another script generated:

* docs/evaluations/portfolio/results.json (``make eval``);
* outputs/onboarding/first-run/REPORT.md (``make onboard NAME=first-run``);
* the newest outputs/incident-drill/*.json (``scripts/incident_drill.py``).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BULLETS = ROOT / "upgrade" / "RESUME_BULLETS.md"
BEGIN = "<!-- bullets:begin (generated by scripts/resume_numbers.py; do not edit) -->"
END = "<!-- bullets:end -->"


def numbers() -> dict[str, object]:
    results = json.loads((ROOT / "docs" / "evaluations" / "portfolio" / "results.json").read_text())
    report = (ROOT / "outputs" / "onboarding" / "first-run" / "REPORT.md").read_text()
    if "| Result | **PASS** |" not in report:
        raise SystemExit("outputs/onboarding/first-run/REPORT.md is not a passing run")
    total = float(re.search(r"\| Total time \| ([\d.]+) s \|", report).group(1))
    migrations = int(re.search(r"\| (\d+) migrations applied", report).group(1))
    verifiers = int(re.search(r"\| (\d+) of \d+ verifiers passed", report).group(1))
    drills = sorted((ROOT / "outputs" / "incident-drill").glob("*.json"))
    if not drills:
        raise SystemExit("no incident drill recorded under outputs/incident-drill/")
    timeline = {item["event"]: item for item in json.loads(drills[-1].read_text())["timeline"]}
    recovery = timeline["/ready returned 200"]["t_seconds"] - timeline["database resumed"]["t_seconds"]
    refused = timeline["journal save during outage"]["status"]
    stored = timeline["entries stored for the drill identity"]["count"]
    benchmark = results["benchmark"]["recomputed"]
    tests = results["tests"]
    return {
        "backend": f"{tests['backend_tests_passed']:,}",
        "coverage": f"{tests['backend_branch_coverage_percent']:.0f}",
        "frontend": tests["frontend_unit_tests_passed"],
        "scenarios": results["benchmark"]["total_scenarios"],
        "wins": benchmark["heldout_candidate_wins"],
        "losses": benchmark["heldout_baseline_wins"],
        "ties": benchmark["heldout_ties"],
        "low": f"{benchmark['heldout_interval_low']:.2f}",
        "high": f"{benchmark['heldout_interval_high']:.2f}",
        "safety_pass": results["safety"]["pass"],
        "safety_total": results["safety"]["total_cases"],
        "migrations": migrations,
        "verifiers": verifiers,
        "onboard_seconds": f"{total:.0f}",
        "refused": refused,
        "stored": stored,
        "recovery": f"{recovery:.0f}",
        "drill": drills[-1].relative_to(ROOT).as_posix(),
    }


def block(values: dict[str, object]) -> str:
    lines = [
        BEGIN,
        "- Built a privacy-first journaling web app with an optional AI companion (FastAPI, PostgreSQL "
        "row-level security, signed writes, Next.js), covered by {backend} backend tests at {coverage}% "
        "branch coverage and {frontend} frontend tests, with README figures regenerated and checked in CI.",
        "- Put a safety and consent gate in front of every model call ({safety_pass} of {safety_total} "
        "development cases pass, reported as not held out) and built an offline evaluation that recomputes "
        "a {scenarios}-scenario model-graded benchmark ({wins} wins, {losses} losses, {ties} ties; 95% "
        "interval {low} to {high}); held the release when one critical case was uncertain.",
        "- Made the service reproducible and operable: one command stands up and verifies a full "
        "environment ({migrations} migrations, {verifiers} database verifiers, a browser demo journey) in "
        "{onboard_seconds} s, and a database-outage drill showed writes refused with HTTP {refused}, "
        "{stored} entry stored after the retry, and readiness restored {recovery} s after recovery.",
        "",
        "Sources: `docs/evaluations/portfolio/results.json`, `outputs/onboarding/first-run/REPORT.md`, "
        "`{drill}`.",
        END,
    ]
    return "\n".join(line.format(**values) for line in lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = BULLETS.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        print(f"{BULLETS.relative_to(ROOT)} has no generated bullets block", file=sys.stderr)
        return 1
    expected = pattern.sub(lambda _: block(numbers()), text)
    if args.write:
        BULLETS.write_text(expected)
        print("resume bullets written")
        return 0
    if expected != text:
        print("resume bullets differ from the generated numbers; run scripts/resume_numbers.py --write",
              file=sys.stderr)
        return 1
    print("resume bullets match the generated numbers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
